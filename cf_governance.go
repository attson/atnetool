// ExportCFGovernanceBundle creates ready-to-use mosdns and 3Proxy
// configurations with the selected edge and current Cloudflare ranges filled
// in. It never changes the system DNS, proxy, hosts file, or service state.
func (a *App) ExportCFGovernanceBundle(result CDNOptimizeResult) (string, error) {
	if a.ctx == nil {
		return "", fmt.Errorf("应用窗口尚未就绪")
	}
	bundle, err := buildCFGovernanceBundle(result)
	if err != nil {
		return "", err
	}
	name := safeGovernanceFilename(result.Domain) + "-cloudflare-governance.zip"
	path, err := wailsruntime.SaveFileDialog(a.ctx, wailsruntime.SaveDialogOptions{
		Title:           "生成 Cloudflare 全局加速配置包",
		DefaultFilename: name,
		Filters:         []wailsruntime.FileFilter{{DisplayName: "ZIP 配置包 (*.zip)", Pattern: "*.zip"}},
	})
	if err != nil || path == "" {
		return path, err
	}
	if err := os.WriteFile(path, bundle, 0o600); err != nil {
		return "", err
	}
	return path, nil
}

func buildCFGovernanceBundle(result CDNOptimizeResult) ([]byte, error) {
	if strings.TrimSpace(result.Domain) == "" {
		return nil, fmt.Errorf("缺少目标域名")
	}
	if result.EffectiveRoute == cdnRouteProxy {
		return nil, fmt.Errorf("该结果来自代理出口，请使用本机网络出口重新测试后再生成直连治理配置")
	}
	if !result.TargetVerification.Verified {
		return nil, fmt.Errorf("目标域名尚未确认使用 Cloudflare 代理")
	}
	if !result.TargetValidated {
		return nil, fmt.Errorf("推荐 IP 尚未通过目标域名验证")
	}
	primary := bestGovernanceProbe(result)
	if primary == nil || net.ParseIP(primary.Candidate.IP) == nil || !primary.Eligible || !primary.VerifiedCloudflare {
		return nil, fmt.Errorf("没有可用于治理的推荐 IP")
	}
	v4, v6 := bestGovernanceIPs(result)
	if v4 == "" && v6 == "" {
		return nil, fmt.Errorf("没有可用于治理的推荐 IP")
	}

	var buffer bytes.Buffer
	writer := zip.NewWriter(&buffer)
	files := []struct {
		name    string
		content []byte
	}{
		{name: "README.txt", content: []byte(buildCFGovernanceReadme(result, primary.Candidate.IP, v4, v6))},
		{name: "mosdns/config.yaml", content: []byte(buildMosDNSConfig(v4, v6))},
		{name: "hosts/current-domain", content: []byte(buildHostsConfig(result.Domain, primary.Candidate.IP, v4, v6))},
		{name: "results/selection.json", content: mustJSON(result)},
	}
	if v4 != "" {
		files = append(files, struct {
			name    string
			content []byte
		}{name: "3proxy/3proxy.cfg", content: []byte(build3ProxyConfig(v4))})
	}
	for _, file := range files {
		entry, err := writer.Create(file.name)
		if err != nil {
			return nil, err
		}
		if _, err := entry.Write(file.content); err != nil {
			return nil, err
		}
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func bestGovernanceProbe(result CDNOptimizeResult) *CDNProbeResult {
	for index := range result.Results {
		if result.Results[index].Candidate.IP == result.BestIP {
			return &result.Results[index]
		}
	}
	for index := range result.Results {
		if result.Results[index].Recommended {
			return &result.Results[index]
		}
	}
	return nil
}

func bestGovernanceIPs(result CDNOptimizeResult) (string, string) {
	var ipv4, ipv6 *CDNProbeResult
	for index := range result.Results {
		probe := &result.Results[index]
		if !probe.Eligible || !probe.VerifiedCloudflare {
			continue
		}
		ip := net.ParseIP(probe.Candidate.IP)
		if ip == nil {
			continue
		}
		if ip.To4() != nil && governanceProbeBetter(probe, ipv4) {
			ipv4 = probe
		}
		if ip.To4() == nil && governanceProbeBetter(probe, ipv6) {
			ipv6 = probe
		}
	}
	var ipv4Value, ipv6Value string
	if ipv4 != nil {
		ipv4Value = net.ParseIP(ipv4.Candidate.IP).String()
	}
	if ipv6 != nil {
		ipv6Value = net.ParseIP(ipv6.Candidate.IP).String()
	}
	return ipv4Value, ipv6Value
}

func governanceProbeBetter(candidate, current *CDNProbeResult) bool {
	if current == nil {
		return true
	}
	if candidate.Recommended != current.Recommended {
		return candidate.Recommended
	}
	if candidate.Rank > 0 && (current.Rank == 0 || candidate.Rank != current.Rank) {
		return candidate.Rank < current.Rank
	}
	return cdnResultLess(false, *candidate, *current)
}

func buildMosDNSConfig(ipv4, ipv6 string) string {
	var ranges strings.Builder
	for _, value := range cloudflareIPv4Ranges {
		fmt.Fprintf(&ranges, "        - %q\n", value)
	}
	for _, value := range cloudflareIPv6Ranges {
		fmt.Fprintf(&ranges, "        - %q\n", value)
	}
	selected := strings.TrimSpace(strings.Join([]string{ipv4, ipv6}, " "))
	return fmt.Sprintf(`# Generated by ATNetool. mosdns v5 standalone configuration.
log:
  level: info

plugins:
  - tag: upstream
    type: forward
    args:
      concurrent: 2
      upstreams:
        - addr: "https://dns.alidns.com/dns-query"
        - addr: "https://doh.pub/dns-query"

  - tag: cloudflare_ranges
    type: ip_set
    args:
      ips:
%s
  - tag: main_sequence
    type: sequence
    args:
      - exec: $upstream
      - matches: resp_ip $cloudflare_ranges
        exec: black_hole %s

  - tag: udp_server
    type: udp_server
    args:
      entry: main_sequence
      listen: 127.0.0.1:5335

  - tag: tcp_server
    type: tcp_server
    args:
      entry: main_sequence
      listen: 127.0.0.1:5335
`, ranges.String(), selected)
}

func build3ProxyConfig(ipv4 string) string {
	ranges := strings.Join(append(append([]string(nil), cloudflareIPv4Ranges...), cloudflareIPv6Ranges...), ",")
	return fmt.Sprintf(`# Generated by ATNetool. Review before enabling as a system proxy.
auth iponly
allow * * %s 443
parent 1000 tcp %s 443
allow *
proxy -p2088 -i127.0.0.1 -46
`, ranges, ipv4)
}

func buildHostsConfig(domain, primary, ipv4, ipv6 string) string {
	var lines []string
	lines = append(lines, fmt.Sprintf("%s %s", primary, domain))
	for _, candidate := range []string{ipv4, ipv6} {
		if candidate != "" && candidate != primary {
			lines = append(lines, fmt.Sprintf("# Alternative: %s %s", candidate, domain))
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

